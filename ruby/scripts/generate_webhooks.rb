#!/usr/bin/env ruby
# frozen_string_literal: true

# Stage-3 generator for lib/factorial_api/webhooks.rb (the typed webhook
# catalog), mirroring typescript/scripts/generate-webhooks.ts and
# python/scripts/generate_webhooks.py.
#
# Reads the OpenAPI spec's top-level `webhooks` object (the RAW spec: the
# normalized one used by openapi-generator has it stripped) and emits:
#
#   - One alias constant per event, pointing at the generated payload model
#     (e.g. F::Api::AtsApplicationCreateWebhook = F::Api::AtsApplication).
#   - F::Api::WEBHOOK_SUBSCRIPTION_TYPES - every valid subscription_type.
#   - F::Api::WEBHOOK_PAYLOAD_TYPES     - subscription_type => payload model class.
#   - F::Api::WEBHOOK_CATALOG           - runtime list of every event.
#
# Each spec webhook entry looks like:
#
#   "Webhooks > Ats > Application > Creates": {
#     "post": {
#       "description": "Subscription_type: `ats/application/create`",
#       "requestBody": {"content": {"application/json": {
#         "schema": {"$ref": "#/components/schemas/ats_application"}}}}
#     }
#   }
#
# Usage (spec source optional - pass a path/URL or set OPENAPI_SPEC_URL;
# defaults to the unversioned endpoint, which serves the latest spec):
#
#   ruby scripts/generate_webhooks.rb [specPathOrUrl]
#
# Also called automatically by scripts/generate_sdk.rb after regeneration.
# Output: lib/factorial_api/webhooks.rb (fully overwritten - never edit).

require 'net/http'
require 'uri'
require 'yaml'

ROOT = File.expand_path('..', __dir__)
OUT = File.join(ROOT, 'lib', 'factorial_api', 'webhooks.rb')
MODELS_DIR = File.join(ROOT, 'lib', 'factorial_api', 'models')
LATEST_SPEC_URL = 'https://api.factorialhr.com/oas/'

def http_get!(url, hops = 3)
  abort("ERROR: too many redirects fetching the spec (#{url})") if hops.zero?

  response = Net::HTTP.get_response(URI(url))
  return http_get!(response['location'], hops - 1) if response.is_a?(Net::HTTPRedirection)

  abort("ERROR: fetching spec failed: HTTP #{response.code} for #{url}") unless response.is_a?(Net::HTTPSuccess)

  response.body
end

# snake_case -> PascalCase, matching openapi-generator's schema -> class naming.
def pascal(snake)
  snake.split('_').reject(&:empty?).map { |part| part[0].upcase + part[1..].to_s }.join
end

# "ats/application/create" -> "AtsApplicationCreateWebhook"
def alias_name(subscription_type)
  "#{subscription_type.split('/').map { |segment| pascal(segment) }.join}Webhook"
end

def load_spec(arg)
  src = arg || ENV.fetch('OPENAPI_SPEC_URL', nil)
  src = nil if src && src.empty?
  src ||= LATEST_SPEC_URL

  puts "Loading OpenAPI spec from #{src}"
  body = src.match?(%r{\Ahttps?://}) ? http_get!(src) : File.read(src, encoding: 'UTF-8')
  spec = YAML.unsafe_load(body)
  puts "Spec version: #{spec.dig('info', 'version') || '<unknown>'}"
  spec
end

spec = load_spec(ARGV[0])
webhooks = spec.fetch('webhooks', {})
abort('ERROR: the spec has no webhooks section (did you pass the normalized spec?)') if webhooks.empty?

entries = webhooks.map do |key, item|
  post = item['post'] or abort("ERROR: webhook #{key.inspect} has no post operation")

  subscription_type = post['description'].to_s[/`([^`]+)`/, 1] or
    abort("ERROR: webhook #{key.inspect} has no subscription_type in its description")

  ref = post.dig('requestBody', 'content', 'application/json', 'schema', '$ref') or
    abort("ERROR: webhook #{key.inspect} has no payload $ref")

  # key = "Webhooks > Ats > Application > Creates"
  _, namespace, resource, event = key.split('>').map(&:strip)

  payload_schema = ref.split('/').last
  {
    subscription_type: subscription_type,
    namespace: namespace.to_s,
    resource: resource.to_s,
    event: event.to_s,
    summary: post['summary'] || key,
    payload_schema: payload_schema,
    payload_class: pascal(payload_schema),
    alias: alias_name(subscription_type)
  }
end

entries.sort_by! { |entry| entry[:subscription_type] }

# --- Sanity guards (fail loudly if the spec shape changes) -------------------
missing = entries.map { |e| e[:payload_schema] }.uniq.reject do |schema|
  File.exist?(File.join(MODELS_DIR, "#{schema}.rb"))
end
abort("ERROR: payload models not present in lib/factorial_api/models: #{missing.join(', ')}") if missing.any?

aliases = entries.map { |e| e[:alias] }
dupes = aliases.tally.select { |_, count| count > 1 }.keys
abort("ERROR: duplicate webhook alias names: #{dupes.join(', ')}") if dupes.any?

distinct_classes = entries.map { |e| e[:payload_class] }.uniq.sort
puts "Parsed #{entries.size} webhook events, #{distinct_classes.size} distinct payload types."

# --- Emit --------------------------------------------------------------------
lines = []
lines << '# frozen_string_literal: true'
lines << ''
lines << '# Typed catalog of every Factorial webhook event and its delivered payload.'
lines << '#'
lines << '# AUTO-GENERATED by scripts/generate_webhooks.rb - DO NOT EDIT.'
lines << '# (scripts/generate_sdk.rb refreshes it on every regeneration)'
lines << '#'
lines << '# Factorial delivers the resource object at the top level of the POST body'
lines << '# (it is NOT wrapped in a {type, data} envelope). The subscription_type and'
lines << '# author are conveyed out-of-band: subscribe with a subscription_type, and'
lines << '# read the x-factorial-author-id / x-factorial-author-type headers if you'
lines << '# need the author.'
lines << '#'
lines << '# Example:'
lines << '#'
lines << '#   payload = F::Api::WEBHOOK_PAYLOAD_TYPES'
lines << "#     .fetch('ats/application/create')"
lines << '#     .build_from_hash(JSON.parse(request.body.read))'
lines << '#   payload.id'
lines << '#'
lines << 'module F; end # namespace prelude: the compact declaration below needs F'
lines << 'module F::Api'
lines << '  # -- Per-event payload aliases ------------------------------------------'
entries.each do |e|
  lines << "  # Payload for `#{e[:subscription_type]}` (#{e[:summary]})."
  lines << "  #{e[:alias]} = #{e[:payload_class]}"
end
lines << ''
lines << '  # -- Every valid subscription_type --------------------------------------'
lines << '  WEBHOOK_SUBSCRIPTION_TYPES = ['
entries.each { |e| lines << "    #{e[:subscription_type].inspect}," }
lines << '  ].freeze'
lines << ''
lines << '  # -- subscription_type => payload model class ---------------------------'
lines << '  WEBHOOK_PAYLOAD_TYPES = {'
entries.each { |e| lines << "    #{e[:subscription_type].inspect} => #{e[:payload_class]}," }
lines << '  }.freeze'
lines << ''
lines << '  # -- Runtime catalog ------------------------------------------------------'
lines << '  # A single Factorial webhook event.'
lines << '  WebhookCatalogEntry = Struct.new('
lines << '    :subscription_type, :namespace, :resource, :event, :summary, :payload_schema,'
lines << '    keyword_init: true'
lines << '  )'
lines << ''
lines << '  WEBHOOK_CATALOG = ['
entries.each do |e|
  lines << '    WebhookCatalogEntry.new('
  lines << "      subscription_type: #{e[:subscription_type].inspect}, namespace: #{e[:namespace].inspect},"
  lines << "      resource: #{e[:resource].inspect}, event: #{e[:event].inspect},"
  lines << "      summary: #{e[:summary].inspect}, payload_schema: #{e[:payload_schema].inspect}"
  lines << '    ),'
end
lines << '  ].freeze'
lines << 'end'
lines << ''

File.write(OUT, lines.join("\n"))
puts "Written #{OUT} (#{lines.size} lines)"
